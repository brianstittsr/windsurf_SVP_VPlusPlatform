import { NextRequest, NextResponse } from "next/server";
import { FieldValue } from "firebase-admin/firestore";
import { adminDb } from "@/lib/firebase-admin";
import { COLLECTIONS, type CaptureSavedSearchDoc } from "@/lib/schema";
import { getCaptureSettings } from "@/lib/capture/settings";
import { scoreMatch, meetsCutoff } from "@/lib/capture/match-score";
import { searchSamOpportunities, type SamNotice } from "@/lib/capture/sam-search";
import { requireUser } from "@/lib/capture/server-auth";
import { captureAudit } from "@/lib/capture/audit";
import type { CustomerDoc } from "@/lib/schema";

const CRON_SECRET = process.env.CRON_SECRET;

/** Procurement types worth matching: presolicitation, solicitation, combined synopsis, sources sought, special notice. */
const DEFAULT_PTYPE = "p,o,k,r,s";

/** Cron Bearer OR an authenticated admin user (manual "run now"). */
async function checkCronAuth(req: NextRequest): Promise<NextResponse | null> {
  const authHeader = req.headers.get("authorization");
  if (CRON_SECRET && authHeader === `Bearer ${CRON_SECRET}`) return null;
  const user = await requireUser(req);
  if (user instanceof NextResponse) return user;
  if (user.role !== "admin") {
    return NextResponse.json({ error: "Forbidden: admin only" }, { status: 403 });
  }
  return null;
}

/**
 * When no active saved searches exist, synthesize one per capture client from
 * its govcon profile (primary NAICS + first keyword) so matching works
 * without manual search setup. Returns the number seeded.
 */
async function seedClientSearches(clients: CustomerDoc[]): Promise<number> {
  if (!adminDb) return 0;
  let seeded = 0;
  for (const client of clients) {
    const g = client.govcon || {};
    const naics = (g.naicsCodes || [])[0];
    const keyword = (g.keywords || [])[0];
    if (!naics && !keyword) continue;
    const name = `Auto: ${client.name || client.id}`;
    const existing = await adminDb
      .collection(COLLECTIONS.CAPTURE_SAVED_SEARCHES)
      .where("name", "==", name)
      .limit(1)
      .get();
    if (!existing.empty) continue;
    await adminDb.collection(COLLECTIONS.CAPTURE_SAVED_SEARCHES).add({
      name,
      query: keyword || undefined,
      naicsCode: naics || undefined,
      ownerId: "system",
      autoGenerated: true,
      isActive: true,
      createdAt: FieldValue.serverTimestamp(),
      updatedAt: FieldValue.serverTimestamp(),
    });
    seeded++;
  }
  return seeded;
}

/**
 * 6-hourly matching cron: runs each active saved search against the SAM
 * opportunities API, scores hits against every capture client, and upserts
 * captureMatches for scores at/above the cutoff.
 */
async function run(): Promise<NextResponse> {
  if (!adminDb) return NextResponse.json({ error: "Database unavailable" }, { status: 500 });
  const settings = await getCaptureSettings();
  const defaultDaysBack = settings.matchLookbackDays ?? 30;

  const clientSnap = await adminDb.collection(COLLECTIONS.CUSTOMERS).get();
  const clients = clientSnap.docs
    .map((d) => ({ id: d.id, ...(d.data() as Omit<CustomerDoc, "id">) }))
    .filter((c) => c.isCaptureClient && !c.deletedAt);

  let searchSnap = await adminDb
    .collection(COLLECTIONS.CAPTURE_SAVED_SEARCHES)
    .where("isActive", "==", true)
    .get();

  let seeded = 0;
  if (searchSnap.empty && clients.length > 0) {
    seeded = await seedClientSearches(clients as CustomerDoc[]);
    if (seeded > 0) {
      searchSnap = await adminDb
        .collection(COLLECTIONS.CAPTURE_SAVED_SEARCHES)
        .where("isActive", "==", true)
        .get();
    }
  }

  if (searchSnap.empty || clients.length === 0) {
    return NextResponse.json({ searches: searchSnap.size, seeded, notices: 0, matches: 0 });
  }

  // Dedupe notices across searches by noticeId
  const seen = new Map<string, SamNotice>();
  const errors: string[] = [];
  for (const s of searchSnap.docs) {
    const q = s.data() as CaptureSavedSearchDoc;
    const { notices, error } = await searchSamOpportunities({
      keyword: q.query || undefined,
      naicsCode: q.naicsCode || undefined,
      setAside: q.setAside || undefined,
      ptype: q.ptype || DEFAULT_PTYPE,
      daysBack: q.daysBack || defaultDaysBack,
      limit: 50,
    });
    if (error) {
      errors.push(`${q.name || s.id}: ${error}`);
      continue;
    }
    for (const n of notices) if (!seen.has(n.noticeId)) seen.set(n.noticeId, n);
    await adminDb
      .collection(COLLECTIONS.CAPTURE_SAVED_SEARCHES)
      .doc(s.id)
      .update({ lastRunAt: FieldValue.serverTimestamp(), lastResultCount: notices.length });
  }

  let created = 0;
  for (const notice of seen.values()) {
    const setAsideLabel = notice.typeOfSetAsideDescription || notice.typeOfSetAside || undefined;
    for (const client of clients) {
      const { score, breakdown } = scoreMatch(
        {
          naicsCode: notice.naicsCode,
          setAside: setAsideLabel,
          agency: notice.department || notice.subTier,
          office: notice.office,
          title: notice.title,
          description: notice.description,
          pscCode: notice.classificationCode,
        },
        client as CustomerDoc,
        settings
      );
      if (!meetsCutoff(score, settings)) continue;

      // Dedupe: one match doc per notice+client
      const existing = await adminDb
        .collection(COLLECTIONS.CAPTURE_MATCHES)
        .where("samNoticeId", "==", notice.noticeId)
        .where("clientId", "==", client.id)
        .limit(1)
        .get();
      if (!existing.empty) continue;

      const ref = await adminDb.collection(COLLECTIONS.CAPTURE_MATCHES).add({
        clientId: client.id,
        clientName: client.name || "",
        samNoticeId: notice.noticeId,
        title: notice.title || "",
        solicitationNumber: notice.solicitationNumber || "",
        agency: notice.department || notice.subTier || "",
        office: notice.office || null,
        naicsCode: notice.naicsCode || null,
        setAside: setAsideLabel || null,
        pscCode: notice.classificationCode || null,
        description: notice.description || null,
        responseDeadline: notice.responseDeadLine || null,
        samUrl: `https://sam.gov/opp/${notice.noticeId}/view`,
        score,
        scoreBreakdown: breakdown,
        status: "pending",
        createdAt: FieldValue.serverTimestamp(),
        updatedAt: FieldValue.serverTimestamp(),
      });
      created++;

      captureAudit({
        type: "create",
        entityType: "capture-match",
        entityId: ref.id,
        entityName: notice.title || notice.noticeId,
        description: `SAM match (${score}) for ${client.name}: ${notice.title || notice.noticeId}`,
        metadata: { clientId: client.id, samNoticeId: notice.noticeId, score },
      });
    }
  }

  return NextResponse.json({
    searches: searchSnap.size,
    seeded,
    notices: seen.size,
    matches: created,
    errors: errors.length ? errors : undefined,
  });
}

export async function GET(req: NextRequest) {
  const authErr = await checkCronAuth(req);
  if (authErr) return authErr;
  return run();
}

export async function POST(req: NextRequest) {
  const authErr = await checkCronAuth(req);
  if (authErr) return authErr;
  return run();
}
