export async function POST(
  request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  if (!adminDb) return NextResponse.json({ error: "Database not initialized" }, { status: 500 });
  const { id } = await params;

  try {
    const body = await request.json() as {
      to?: string;
      cc?: string[];
      subject?: string;
      message?: string;
    };

    const doc = await adminDb.collection(COLLECTIONS.ZENTHIUM_OPPORTUNITIES).doc(id).get();
    if (!doc.exists) return NextResponse.json({ error: "Opportunity not found" }, { status: 404 });

    const opp = doc.data() as Record<string, unknown>;
    const toEmail = body.to ?? "joshua@zenthium.ai";
    const ccEmails: string[] = body.cc ?? [];
    const subject = body.subject ?? `Powered Land Intake — ${opp.propertyName ?? "Property"} — ${opp.city ?? ""}, ${opp.state ?? ""}`;
    const intakeText = buildIntakeText(opp);
    const intakeBase64 = Buffer.from(intakeText).toString("base64");
    const htmlBody = buildIntakeEmailHTML(opp);

    const RESEND_API_KEY = process.env.RESEND_API_KEY;

    if (RESEND_API_KEY) {
      const emailPayload: Record<string, unknown> = {
        from: "Zenthium Platform <noreply@strategicvalueplus.com>",
        to: [toEmail],
        subject,
        html: htmlBody + (body.message ? `<br/><hr/><p>${body.message}</p>` : ""),
        attachments: [
          {
            filename: `${(opp.propertyName as string ?? "Intake").replace(/[^a-z0-9]/gi, "_")}_Intake.txt`,
            content: intakeBase64,
          },
        ],
      };
      if (ccEmails.length > 0) emailPayload.cc = ccEmails;

      const emailRes = await fetch("https://api.resend.com/emails", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${RESEND_API_KEY}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify(emailPayload),
      });

      if (!emailRes.ok) {
        const err = await emailRes.text();
        console.error("[Zenthium] Resend error:", err);
        return NextResponse.json({ error: "Email send failed" }, { status: 500 });
      }
    } else {
      console.log("=== ZENTHIUM INTAKE EMAIL (no RESEND_API_KEY) ===");
      console.log(`To: ${toEmail}`);
      if (ccEmails.length) console.log(`CC: ${ccEmails.join(", ")}`);
      console.log(`Subject: ${subject}`);
      console.log(`Property: ${opp.propertyName} — ${opp.city}, ${opp.state}`);
      console.log("=================================================");
    }

    await adminDb.collection(COLLECTIONS.ZENTHIUM_OPPORTUNITIES).doc(id).update({
      intakeSentAt: Timestamp.now(),
      intakeSentTo: [toEmail],
      intakeSentCC: ccEmails,
      status: "sent",
      updatedAt: Timestamp.now(),
    });

    return NextResponse.json({ success: true, sentTo: toEmail, cc: ccEmails });
  } catch (error) {
    console.error("[Zenthium] send-intake error:", error);
    return NextResponse.json({ error: "Failed to send intake" }, { status: 500 });
  }
}
